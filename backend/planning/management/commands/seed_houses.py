class Command(BaseCommand):
    help = "Seed architectural style catalog (procedural Three.js designs)."

    def handle(self, *args, **options):
        # Deactivate legacy thin catalog names that conflict with new naming
        legacy = [
            "Compact Cottage",
            "Modern Family Home",
            "Contemporary Villa",
            "Italian Villa",
        ]
        HouseDesign.objects.filter(name__in=legacy).update(active=False)

        for row in DESIGNS:
            obj, created = HouseDesign.objects.update_or_create(
                name=row["name"], defaults=row
            )
            self.stdout.write(("Created" if created else "Updated") + ": " + obj.name)

        self.stdout.write(self.style.SUCCESS("Styles: " + ", ".join(STYLES.keys())))
        self.stdout.write(self.style.SUCCESS("Active designs: {}".format(
            HouseDesign.objects.filter(active=True).count()
        )))
