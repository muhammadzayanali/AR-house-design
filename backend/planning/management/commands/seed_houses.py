def _cfg(style_key, floors, width, depth, features):
    return {
        "style": style_key,
        "floors": floors,
        "footprint": {"width": width, "depth": depth},
        "features": features,
    }


def _row(**kwargs):
    w = kwargs["building_width_m"]
    d = kwargs["building_depth_m"]
    kwargs.setdefault("building_footprint_sqm", round(w * d, 1))
    kwargs.setdefault("min_plot_area_sqm", kwargs["recommended_min_plot"])
    kwargs.setdefault("max_plot_area_sqm", kwargs["recommended_max_plot"])
    kwargs.setdefault("model_type", HouseDesign.MODEL_PROCEDURAL)
    kwargs.setdefault("source_provider", "plotline-procedural")
    kwargs.setdefault("source_license", "project-generated")
    kwargs.setdefault("currency", "PKR")
    kwargs.setdefault("active", True)
    kwargs.setdefault("parking", kwargs.get("parking_spaces", 0) > 0)
    kwargs.setdefault("glb_url", "")
    return kwargs


